const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const storage=new Map();
function createContext(){
  const c=vm.createContext({console,crypto:require('node:crypto'),document:{addEventListener(){}},window:{addEventListener(){}},sessionStorage:{getItem:key=>storage.get(key)||null,setItem:(key,value)=>storage.set(key,value)}});
  vm.runInContext(fs.readFileSync(path.join(__dirname,'../app.js'),'utf8').replace(/writeAppHistory\("home", true\);\s*restoreSession\(\);\s*$/,''),c);
  vm.runInContext(fs.readFileSync(path.join(__dirname,'../sales.js'),'utf8'),c);
  vm.runInContext(`render=()=>{};state.mode='vendas';state.loggedIn=true;state.userEmail='test@example.com';`,c);
  return c;
}
let context=createContext();
const run=code=>vm.runInContext(code,context);
run('requestNewSale()');
assert.equal(run('salesState.confirmNew'),false);
assert.equal(run('salesState.phase'),'scan');
run(`salesState.items=[{code:'10255',name:'Set',price:'300',locations:[{storage:'Feira',stock:2}],allocations:{Feira:1}}];salesState.customer={name:'Client',tax:'001234567'};salesState.type='Factura';salesState.phase='customer';persistSaleDraft();openSalesMenu();requestNewSale();`);
assert.equal(run('salesState.confirmNew'),true);
assert.ok(run('salesMarkup().includes(' + JSON.stringify('Já existe uma venda em progresso') + ')'));
assert.ok(run('salesMarkup().includes("CONTINUAR VENDA")'));
assert.ok(run('salesMarkup().includes(' + JSON.stringify('COMEÇAR NOVA') + ')'));
assert.equal(run('salesState.items[0].price'),'300','Opening the choice must not discard the draft');
run('resumeSaleDraft()');
assert.equal(run('salesState.phase'),'customer');
assert.equal(run('salesState.customer.tax'),'001234567');
assert.equal(run('salesState.type'),'Factura');
run(`salesState.phase='list';persistSaleDraft();openSalesMenu();requestNewSale();resumeSaleDraft();`);
assert.equal(run('salesState.phase'),'customer','Consulting saved sales must preserve the draft stage');
context=createContext();
assert.equal(run('salesState.showMenu'),true);
run('requestNewSale()');
assert.equal(run('salesState.confirmNew'),true,'Recover an unfinished sale after reload');
run('resumeSaleDraft()');
assert.equal(run('salesState.phase'),'customer');
assert.equal(run('salesState.items[0].allocations.Feira'),1);
run(`salesState.pending={item:{code:'200',price:'',allocations:{Feira:1}}};salesState.phase='scan';persistSaleDraft();openSalesMenu();requestNewSale();`);
assert.equal(run('salesState.confirmNew'),true,'An unconfirmed price also counts as an active sale');
run('resumeSaleDraft()');
assert.equal(run('salesState.pending.item.code'),'200');
run('requestNewSale();startNewSale()');
assert.equal(run('salesState.items.length'),0);
assert.equal(run('salesState.pending'),null);
assert.equal(run('Object.keys(salesState.customer).length'),0);
assert.equal(run('salesState.type'),'');
run(`salesState.items=[{code:'100',allocations:{A:1},price:'10'}];salesState.saved=['completed-sale'];salesState.phase='saved';requestNewSale();`);
assert.equal(run('salesState.confirmNew'),false,'A completed sale must not trigger the warning');
assert.equal(run('salesState.items.length'),0);
run(`salesState.items=[{code:'100',allocations:{A:1},price:'10'}];salesState.uncertain=true;salesState.id='in-flight';requestNewSale();startNewSale();`);
assert.equal(run('salesState.id'),'in-flight','Never discard a sale whose submission result is unknown');
assert.equal(run('salesState.items.length'),1);
assert.equal(run('salesState.phase'),'customer');
run(`salesState.uncertain=false;startNewSale();salesState.items=[{code:'100',name:'Set',price:'10',locations:[{storage:'A',stock:1}],allocations:{A:1}}];salesState.phase='document';`);
assert.equal(run('salesTitle()'),'DOCUMENTO');
assert.ok(!run('salesMarkup().includes("data-sale-customer")'),'Document selection must not show customer fields');
assert.ok(run('salesMarkup().includes(' + JSON.stringify('name="customer" disabled') + ')'));
assert.throws(()=>run('continueSaleDocument()'),/Seleciona/);
assert.equal(run('salesState.phase'),'document');
run(`salesState.type='Recibo';persistSaleDraft();`);
assert.ok(!run('salesMarkup().includes(' + JSON.stringify('name="customer" disabled') + ')'));
assert.ok(!run('salesMarkup().includes("data-sale-customer")'),'Selecting a document must still wait for Continue');
run('openSalesMenu();requestNewSale();resumeSaleDraft();');
assert.equal(run('salesState.phase'),'document','Restore the document selection stage');
run('continueSaleDocument()');
assert.equal(run('salesState.phase'),'customer');
assert.equal(run('salesTitle()'),'DADOS DO CLIENTE');
assert.ok(run('salesMarkup().includes("data-sale-customer")'));
assert.ok(!run('salesMarkup().includes("data-sale-field=\\"type\\"")'));
console.log('Sales draft tests passed: continue, replace, pending prices, listing, reload, completed sales and uncertain submissions.');
