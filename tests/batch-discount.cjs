const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const c=vm.createContext({console,crypto:require('node:crypto'),document:{addEventListener(){},querySelector(){return null}},window:{addEventListener(){}}});
vm.runInContext(fs.readFileSync(require('node:path').join(__dirname,'../app.js'),'utf8').replace(/writeAppHistory\("home", true\);\s*restoreSession\(\);\s*$/,''),c);
const run=s=>vm.runInContext(s,c),plan=(items,type,value)=>JSON.parse(run(`JSON.stringify(batchDiscountPlan(${JSON.stringify(items)},${JSON.stringify(type)},${JSON.stringify(value)}))`));
const items=[{code:'A',qty:2,cost:100},{code:'B',qty:1,cost:300}];
assert.deepEqual(plan(items,'percent',20).costs,[80,240]);
assert.deepEqual(plan(items,'amount',200).costs,[60,180]);
assert.equal(plan(items,'amount',200).target,30000);
assert.deepEqual(plan(items,'percent',100).costs,[0,0]);
assert.deepEqual(plan([{qty:1,cost:0},{qty:2,cost:10}],'amount',10).costs,[0,5]);
const roundingItems=[{qty:3,cost:1},{qty:2,cost:1}],r=plan(roundingItems,'amount',.01);
assert.equal(Math.round(r.costs.reduce((sum,cost,i)=>sum+cost*roundingItems[i].qty,0)*100),499);
assert.deepEqual(plan(items,'amount',0).costs,[100,300]);
for(const [type,value] of [['percent',101],['percent',-1],['amount',501],['amount',''],['amount','bad']])assert.throws(()=>plan(items,type,value));
assert.throws(()=>plan([{qty:1,cost:''}],'amount',1));
assert.throws(()=>plan([{qty:0,cost:1}],'amount',1));
assert.equal(items[0].cost,100,'Planning must not mutate costs before confirmation');
run(`state.mode='lote';state.batch={...emptyBatchState(),movementType:'entrada',items:[{code:'A',name:'Set A',qty:2,cost:100}]};`);
assert.ok(run(`batchConditionsMarkup().includes('data-action="batch-discount"')`));
run(`state.batch.movementType='saida';state.batch.items[0].locations=[];state.batch.items[0].allocations={};`);
assert.ok(!run(`batchConditionsMarkup().includes('data-action="batch-discount"')`));
console.log('Batch discount tests passed: percentage, weighted amount, zero costs, limits and exact total rounding');
run(`state.batch.movementType='entrada';state.batch.items=[{code:'A',name:'A',qty:2,cost:'100'},{code:'B',name:'B',qty:1,cost:'300'}];applyBatchDiscount('A',false,'percent',20);`);
assert.equal(run('state.batch.items[0].cost'),'80');assert.equal(run('state.batch.items[1].cost'),'300');
run(`state.batch.items[0].cost='100';applyBatchDiscount('A',true,'amount',200)`);
assert.equal(run('state.batch.items[0].cost'),'60');assert.equal(run('state.batch.items[1].cost'),'180');
run(`state.batch.items[0].cost='100';state.batch.items[1].cost='';applyBatchDiscount('A',false,'amount',20)`);
assert.equal(run('state.batch.items[0].cost'),'90','Individual amount applies across the selected item quantity');
assert.equal(run('state.batch.items[1].cost'),'','Individual discounts do not require unrelated prices');
assert.throws(()=>run(`applyBatchDiscount('A',true,'percent',20)`));
assert.equal(run('state.batch.items[0].cost'),'90','Invalid global input must not partially change costs');
assert.equal(run(`(batchConditionsMarkup().match(/data-action="batch-discount"/g)||[]).length`),2);
assert.ok(!run(`batchConditionsMarkup().includes('batch-discount-actions')`));
run(`state.batch.items=[{code:'A',name:'Set A',qty:1,cost:'100'},{code:'B',name:'Set B',qty:1,cost:'200'}];applyBatchDiscount('A',false,'percent',20);`);
assert.equal(run('state.batch.items[0].entryOriginalCost'),100);
assert.equal(run('state.batch.items[1].entryOriginalCost'),undefined);
assert.ok(run(`batchEntryPriceMarkup(state.batch.items[0],0).includes('Original: <s>100,00')`));
assert.ok(run(`batchEntryPriceMarkup(state.batch.items[0],0).includes('Com desconto: 80,00')`));
run(`applyBatchDiscount('A',false,'percent',10)`);
assert.equal(run('state.batch.items[0].entryOriginalCost'),100,'Keep the original price across repeated discounts');
assert.equal(run('state.batch.items[0].cost'),'72');
assert.equal(run('JSON.parse(JSON.stringify(state.batch)).items[0].entryOriginalCost'),100);