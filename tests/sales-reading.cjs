const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const listeners = {};
const context=vm.createContext({console,crypto:require('node:crypto'),localStorage:{getItem(){return null}},sessionStorage:{getItem(){return null},setItem(){}},document:{addEventListener(type,handler){(listeners[type]||=[]).push(handler)},querySelector(){return {focus(){}}}},window:{addEventListener(){}}});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../app.js'),'utf8').replace(/writeAppHistory\("home", true\);\s*restoreSession\(\);\s*$/,''),context);
vm.runInContext(fs.readFileSync(path.join(__dirname,'../sales.js'),'utf8'),context);
const run=code=>vm.runInContext(code,context);
run(`state.mode='vendas';state.loggedIn=true;state.userEmail='test@example.com';state.accessToken='test';render=()=>{};
  const readingStock=[['100','','','','','','','A',2,'','','','',5,'','Com factura'],['100','','','','','','','B',2,'','','','',8,'','Com factura']];
  loadMovementStockRows=async()=>readingStock;
  findSet=code=>code==='100'||code==='5700000000000'?{code:'100',name:'Test set',ean:'5700000000000'}:undefined;`);
assert.ok(run('salesMarkup().includes("batch-movement-actions")'));
assert.ok(run('salesMarkup().includes("NOVA VENDA")'));
assert.ok(run('salesMarkup().includes(">CONSULTAR VENDAS<")'));
assert.ok(!run('salesMarkup().includes("number-grid")'),'Sales entry must show only the menu');
assert.ok(run('headerMarkup().includes(">VENDAS</h1>")'));
assert.ok(run('headerMarkup().includes("data-action=\\"home\\"")'));
const saleClick=listeners.click.at(-2);
saleClick({target:{closest(){return {dataset:{saleAction:'new'}}}}});
assert.ok(run('salesMarkup().includes("number-grid")'));
assert.ok(run('headerMarkup().includes(">NOVA VENDA</h1>")'));
assert.ok(run('salesMarkup().includes("data-action=\\"scanner\\"")'));
const key=listeners.keydown.at(-1);
for(const digit of '100')key({key:digit,target:{closest(){return null}},preventDefault(){}});
assert.equal(run('state.query'),'100');
(async()=>{
  await run('lookup()');
  assert.equal(run('state.query'),'');
  assert.equal(run('salesState.items.length'),0,'Do not add until the price is confirmed');
  assert.equal(run('salesState.pending.item.allocations.A'),1);
  run(`adjustSaleLocation('pending',0,1);adjustSaleLocation('pending',0,1);`);
  assert.equal(run('salesState.pending.item.allocations.A'),1,'Location controls cannot increase the quantity sold');
  run(`adjustSaleLocation('pending',1,1);`);
  assert.equal(run('salesState.pending.item.allocations.A'),0);
  assert.equal(run('salesState.pending.item.allocations.B'),1,'Increasing B must transfer a unit from A');
  run(`adjustSaleLocation('pending',0,1);adjustSaleLocation('pending',1,-1);`);
  assert.equal(run('salesState.pending.item.allocations.A'),1);
  assert.equal(run('salesState.pending.item.allocations.B'),0,'Location quantities cannot be negative');
  run(`setSaleLocation('pending',1,2);`);
  assert.equal(run('salesState.pending.item.allocations.B'),1,'Typed quantities must preserve the total too');
  run(`setSaleLocation('pending',1,0);`);
  assert.equal(run('salesState.pending.item.allocations.A'),1,'Decreasing a location transfers stock back to another location');
  assert.ok(run('salesMarkup().includes("sale-price-form")'));
  assert.equal(run('salesTitle()'),'PREÇO DE VENDA');
  assert.ok(!run('salesMarkup().includes("number-grid")'));
  await run('addSaleCode("100")');
  assert.equal(run('salesState.items.length'),0,'Block further reads while waiting for a price');
  assert.throws(()=>run('confirmSalePrice()'),/preços/);
  run(`salesState.pending.item.price='10.10';confirmSalePrice();`);
  assert.equal(run('salesState.items.length'),1);
  assert.equal(run('saleUnitCount()'),1);
  await run('addSaleCode("5700000000000")');
  run(`salesState.pending.item.price='10.10';confirmSalePrice();`);
  assert.equal(run('salesState.items.length'),1,'Same article and price merge');
  assert.equal(run('saleUnitCount()'),2);
  await run('addSaleCode("100")');
  assert.equal(run('salesState.pending.item.allocations.B'),1,'Skip stock already allocated in the sale');
  run(`salesState.pending.item.price='20';confirmSalePrice();`);
  assert.equal(run('salesState.items.length'),2,'Different prices retain separate lines');
  assert.equal(run('saleTotal(salesState.items)'),4020);
  run(`salesState.phase='review';`);
  assert.equal(run('salesTitle()'),'REVER VENDA');
  assert.ok(run('salesMarkup().includes("data-sale-action=\\"edit-price\\"")'));
  assert.ok(run('salesMarkup().includes("CONTINUAR LEITURA")'));
  run(`salesState.phase='customer';salesState.type='Recibo';salesState.customer={name:'Client',address:'Street',email:'a@example.com',phone:'123',tax:'001'};salesState.seller='Old draft seller';const readingRows=buildSaleRows(readingStock,'sale','date');`);
  assert.equal(run('salesTitle()'),'DADOS DO CLIENTE');
  assert.equal(run('readingRows.sale[12]'),'','Seller must come from the hardcoded configuration');
  assert.ok(!run('salesMarkup().includes("data-sale-field=\\"seller\\"")'));
  assert.equal(run('readingRows.lines.length'),2);
  assert.equal(run('readingRows.movements.reduce((sum,r)=>sum+r[11],0)'),-3);
  run(`salesState.items[1].allocations.B=3;`);
  assert.throws(()=>run(`buildSaleRows(readingStock,'sale','date')`),/stock/);
  run(`salesState.items[1].allocations.B=1;salesState.items[1].allocations.A=1;`);
  assert.throws(()=>run(`buildSaleRows(readingStock,'sale','date')`),/stock/,'Revalidate aggregate stock across differently priced lines');
  run(`salesState.phase='list';`);
  assert.equal(run('salesTitle()'),'CONSULTAR VENDAS');
  run(`salesState.phase='saved';`);
  assert.equal(run('salesTitle()'),'VENDA REGISTADA');
  run(`openSalesMenu();`);
  assert.equal(run('salesTitle()'),'VENDAS');
  assert.ok(!run('salesMarkup().includes("number-grid")'));
  run(`salesState.items=[{code:'X',price:'10',locations:[{storage:'Feira',stock:2},{storage:'TestLoc',stock:1}],allocations:{Feira:1,TestLoc:0}}];adjustSaleLocation(0,1,1);`);
  assert.equal(run('salesState.items[0].allocations.Feira'),0);
  assert.equal(run('salesState.items[0].allocations.TestLoc'),1);
  assert.equal(run('saleUnitCount()'),1);
  assert.equal(run('saleTotal(salesState.items)'),1000,'Redistributing locations must preserve the sale total');
  run(`adjustSaleQuantity(0,1);`);
  assert.equal(run('saleUnitCount()'),2,'Only the article quantity control changes units sold');
  run(`salesState.items.push({code:'X',price:'20',locations:[{storage:'Feira',stock:2},{storage:'TestLoc',stock:1}],allocations:{Feira:1,TestLoc:0}});adjustSaleLocation(0,1,-1);`);
  assert.equal(run('salesState.items[0].allocations.TestLoc'),1,'Do not transfer into capacity reserved by another line');
  run(`setSaleItemPrice(0,'13.25');`);
  assert.equal(run('salesState.items[0].price'),'13.25');
  assert.equal(run('saleUnitCount()'),3,'Changing the price must not change quantities');
  assert.equal(run('saleTotal(salesState.items)'),4650);
  assert.throws(()=>run(`setSaleItemPrice(0,'1.001')`),/preços/);
  console.log('Sales reading tests passed: shared keypad/scanner route, price pause, merging, separate prices, review, seller configuration and aggregate stock.');
})().catch(error=>{console.error(error);process.exitCode=1});
