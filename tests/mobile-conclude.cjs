const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require('node:path').join(__dirname, '../app.js'), 'utf8').replace(/writeAppHistory\("home", true\);\s*restoreSession\(\);\s*$/, '');
const context = vm.createContext({ console, document: { addEventListener() {}, querySelector() { return null; } }, window: { addEventListener() {} } });
vm.runInContext(source, context);
const run = code => vm.runInContext(code, context);
run(`
 let mobile=true, clicks=0, bounds={top:700,bottom:750};
 const original={disabled:false,getBoundingClientRect:()=>bounds,click:()=>clicks++};
 const content={querySelector:()=>original,getBoundingClientRect:()=>({top:64,bottom:640})};
 const header={getBoundingClientRect:()=>({bottom:64})};
 let floating, observer, disconnected=0;
 document.createElement=()=>({style:{},addEventListener(type,fn){this.click=fn},remove(){floating=null}});
 document.querySelector=selector=>selector==='.app-content'?content:selector==='.lot-mobile-header'?header:selector==='.mobile-conclude-button'?floating:selector==='#app'?{append(button){floating=button}}:null;
 window.matchMedia=()=>({matches:mobile});
 window.IntersectionObserver=class {constructor(callback){observer=callback}observe(){}disconnect(){disconnected++}};
 state.mode='lote';setupMobileConcludeButton();
`);
assert.equal(run('floating.hidden'), false);
assert.equal(run('floating.style.top'), '74px');
run('floating.click()');
assert.equal(run('clicks'), 1);
run('bounds={top:550,bottom:600};observer()');
assert.equal(run('floating.hidden'), true);
run('bounds={top:620,bottom:670};observer()');
assert.equal(run('floating.hidden'), false);
run('original.disabled=true;observer()');
assert.equal(run('floating.hidden'), true);
run('original.disabled=false;mobile=false;updateMobileConcludeButton()');
assert.equal(run('floating.hidden'), true);
run('mobile=true;state.scannerOpen=true;updateMobileConcludeButton()');
assert.equal(run('floating.hidden'), true);
run('state.scannerOpen=false;setupMobileConcludeButton()');
assert.equal(run('disconnected'), 1);
run('state.mode=null;setupMobileConcludeButton()');
assert.equal(run('floating'), null);
console.log('Mobile conclude tests passed: visibility, clipping, disabled state, desktop, camera, click forwarding and cleanup.');
